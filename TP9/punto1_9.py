def suma(b,a):
	sum = b+a
	return sum

def letras(nombre):
	cantidad = len(nombre)
	return cantidad
	
def expo(b,a):
	pot = b**a
	return pot
	
def mayus(n):
	return n.upper()
	
def mayus_minus(m,ma):
	may = m.upper()
	mi = ma.lower()
	return may,mi
	
def mas_let(nom1,nom2):
	nom1 = len(nom1)
	nom2 = len(nom2)
	return nom1, nom2
